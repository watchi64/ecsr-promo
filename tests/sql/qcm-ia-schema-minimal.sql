-- Schema minimal pour jouer 20261023_qcm_ia.sql et sa preuve sur une base Postgres LOCALE
-- jetable (jamais en prod). Reprend de la prod ce dont la migration depend : roles Supabase,
-- auth.jwt() / auth.uid(), is_admin() (definition copiee le 23/10), et les colonnes utiles des
-- tables qcm, qcm_questions, qcm_options, cours, themes, user_profiles, profs, stagiaires.
-- Lancement : voir l'en-tete de tests/sql/qcm-ia-preuve.sql.

do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin bypassrls; end if;
end $$;

create schema if not exists auth;
grant usage on schema auth, public to anon, authenticated, service_role;
create table if not exists auth.users (id uuid primary key, email text);
create or replace function auth.jwt() returns jsonb language sql stable as $$
  select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
create or replace function auth.uid() returns uuid language sql stable as $$
  select nullif(auth.jwt() ->> 'sub', '')::uuid $$;
grant execute on all functions in schema auth to anon, authenticated, service_role;

-- Comme Supabase : tout nouvel objet de public est accorde aux roles d'API (la RLS filtre).
alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema public grant execute on functions to anon, authenticated, service_role;

create table public.profs (id serial primary key, nom text not null);
create table public.stagiaires (id serial primary key, prenom text not null);
create table public.user_profiles (
  email text primary key, role text, is_admin boolean default false, is_founder boolean default false,
  prof_id integer references public.profs(id), stagiaire_id integer references public.stagiaires(id));
create table public.themes (id serial primary key, numero integer, titre text not null);
create table public.cours (
  id uuid primary key default gen_random_uuid(), numero integer unique, code text unique,
  titre text not null, corps_md text not null, published boolean not null default false);
create table public.qcm (id bigint generated by default as identity primary key,
  theme_id integer not null, titre text not null);
create table public.qcm_questions (
  id bigint generated by default as identity primary key,
  qcm_id bigint not null references public.qcm(id) on delete cascade,
  section text, enonce text not null, explication text, ordre integer not null default 0,
  created_at timestamptz not null default now(), image_url text);
create table public.qcm_options (
  id bigint generated by default as identity primary key,
  question_id bigint not null references public.qcm_questions(id) on delete cascade,
  texte text not null, is_correct boolean not null default false, ordre integer not null default 0);

-- RLS de la prod sur les questions : lecture ouverte a tout connecte, ecriture admin.
alter table public.qcm_questions enable row level security;
create policy qcm_questions_select_connectes on public.qcm_questions for select to authenticated using (true);
alter table public.qcm_options enable row level security;
create policy qcm_options_select_connectes on public.qcm_options for select to authenticated using (true);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from user_profiles
    where lower(email) = lower((select auth.jwt() ->> 'email'))
      and is_admin = true
  );
$$;
